// Writes engines-fitted.js from tools/fitted-<id>.json: the sound settings the fit changed,
// layered over the hand-written defaults in engines.js.
//   node tools/apply-fit.js gt3 gtr f458

const path = require('path'), fs = require('fs');
const root = path.join(__dirname, '..');
const ids = process.argv.slice(2);
const out = {};
for (const id of ids) {
  const { changed, cfg } = JSON.parse(fs.readFileSync(path.join(__dirname, `fitted-${id}.json`)));
  const o = {};
  for (const [p, [, v]] of Object.entries(changed)) if (p !== 'cylSpread') o[p] = v;
  if (changed.cylSpread) o.firing = cfg.firing.map((f) => ({ ...f, gain: +f.gain.toFixed(4), runnerMs: +f.runnerMs.toFixed(4) }));
  out[id] = o;
}
const src = `// Generated by tools/apply-fit.js from fits against real recordings (see README). Do not edit by hand:
// re-run the fit instead. Each entry overrides a setting in engines.js.
const FITTED_SOUND = ${JSON.stringify(out, null, 1)};

function applyFitted(E) {
  for (const [id, f] of Object.entries(FITTED_SOUND)) {
    const s = E[id] && E[id].sound;
    if (!s) continue;
    for (const [p, v] of Object.entries(f)) {
      if (p === 'firing') { s.firing = v; continue; }
      const ks = p.split('.'), last = ks.pop();
      ks.reduce((o, k) => o[k], s)[last] = v;
    }
  }
  return E;
}

if (typeof module !== 'undefined') module.exports = applyFitted;
else if (typeof ENGINES !== 'undefined') applyFitted(ENGINES);
`;
fs.writeFileSync(path.join(root, 'engines-fitted.js'), src);
console.log('wrote engines-fitted.js for ' + ids.join(', '));
